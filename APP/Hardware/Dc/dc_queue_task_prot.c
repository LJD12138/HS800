/***********************************************************************************************************************
 * 函数功能    : DC 队列任务: 保护扫描
 * 说明(备注)  : ADC 越限哨兵提前唤醒；立即执行一次保护扫描，判据仍由滤波计数确认
 * 传入参数    : p_task: 队列任务控制块
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void v_dc_queue_task_prot(Task_T *p_task)
{
	/* 有更高优先级任务投递, 让出执行 */
	if (lwrb_get_full(&p_task->tQueueBuff))
	{
		cQueue_GotoStep(p_task, STEP_END);
		return;
	}

	/* 立即执行一次保护扫描后结束，交还默认任务(轮询引擎提供空闲节拍) */
	vDc_ProtectProcess();
	cQueue_GotoStep(p_task, STEP_END);
}

#endif  /* boardDC_EN */
