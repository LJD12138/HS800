{
    #if (boardUSE_OS)
    return (uint32_t)(xTaskGetTickCount() * portTICK_PERIOD_MS);
    #else
    return 0U;
    #endif  /* boardUSE_OS */
}

/***********************************************************************************************************************
 * 函数功能    : 系统初始化就绪判定
 * 说明(备注)  : 显示任务 INIT 页跑通后置位, 作为 INIT 步完成条件 (未就绪保持 INIT 步)
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : true: 系统就绪, false: 初始化未完成
 ************************************************************************************************************************/
bool bDisp_PortIsSystemReady(void)
{
    return (tSysInfo.uInit.tFinish.bIF_DispTask != 0);
}

/***********************************************************************************************************************
 * 函数功能    : overlay 激活判定适配
 * 说明(备注)  : 项目件指定 overlay 触发条件, 框架每帧电平评估压入/弹出 (本工程: 设备状态为 DS_ERR);
 *               未就绪门控: 系统初始化完成前不弹 overlay (与场景映射门控一致, 只允许 INIT 页),
 *               故障待就绪后由电平评估下一帧补入; 后续扩展只需改本函数, 通用件零修改
 * 传入参数    : p_snapshot: [IN] 帧数据快照
 * 输出参数    : 无
 * 返回值      : true: overlay 激活 (压入), false: 未激活 (可弹出)
 ************************************************************************************************************************/
bool bDisp_PortIsOverlayActive(const DispDataSnapshot_T *p_snapshot)
{
    if (p_snapshot == NULL)
        return false;

    return (bDisp_PortIsSystemReady() && (ucDisp_DataDevState(p_snapshot) == DS_ERR));
}

