/***********************************************************************************************************************
 * 函数功能    : 切页后内存审计 (LVGL 内存池水位/碎片率)
 * 说明(备注)  : 仅显示任务上下文调用 (LVGL 单上下文); 空闲低于阈值或碎片率超限时打印并计数,
 *               用于尽早发现页面 vOnExit 漏释放对象
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortMemAudit(void)
{
    lv_mem_monitor_t t_mon;

    lv_mem_monitor(&t_mon);

    if ((t_mon.free_size < dispMEM_FREE_MIN_BYTES) || (t_mon.frag_pct > dispMEM_FRAG_MAX_PCT))
    {
        S_ulMemAuditWarnCnt++;

        if (uPrint.tFlag.bDispTask)
        {
            sMyPrint("DispMemAudit: warn=%lu free=%u frag=%u%% used=%u%%\r\n",
                     (unsigned long)S_ulMemAuditWarnCnt,
                     (unsigned int)t_mon.free_size,
                     (unsigned int)t_mon.frag_pct,
                     (unsigned int)t_mon.used_pct);
        }
    }
}

