/***********************************************************************************************************************
 * 函数功能    : 获取毫秒时基
 * 说明(备注)  : OS 环境直接复用 FreeRTOS 节拍 (configTICK_RATE_HZ=1000 → 1 tick = 1ms);
 *               裸机项目应返回自有 1ms 计数, 返回 0 时框架退回按帧周期累计驻留时间
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 毫秒时间戳
 ************************************************************************************************************************/
