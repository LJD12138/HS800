//****************************************************Parameter Initialization**************************************************//
#if (boardUSE_OS)
static TaskHandle_t S_tDispTaskHandle = NULL;
#endif  //boardUSE_OS

//****************************************************Function Declaration******************************************************//

/***********************************************************************************************************************
 * 函数功能    : 渲染输出原语适配
 * 说明(备注)  : 转调项目件 vDisp_UiRefresh (EEZ ui_tick -> 自绘动画 -> lv_timer_handler)
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortUiRefresh(void)
{
    vDisp_UiRefresh();
}

/***********************************************************************************************************************
 * 函数功能    : 背光硬件开关适配
 * 说明(备注)  : 转调项目件接口层 vDisp_SetBacklight
 * 传入参数    : on: true-点亮, false-熄灭
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortSetBacklight(bool on)
{
    vDisp_SetBacklight(on);
}

/***********************************************************************************************************************
 * 函数功能    : 获取持久化自动息屏时间
 * 说明(备注)  : 息屏策略数据源 (0=常亮), 框架亮/息屏时读取
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 自动息屏时间 (秒)
 ************************************************************************************************************************/
uint16_t usDisp_PortGetAutoOffTime(void)
{
    return tAppMemParam.tDISP.usAutoOffTime;
}

/***********************************************************************************************************************
 * 函数功能    : 系统初始化就绪判定
 * 说明(备注)  : 显示任务 INIT 页跑通后置位, false 时框架锁定 INIT 页
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : true: 系统就绪, false: 初始化未完成
 ************************************************************************************************************************/
bool bDisp_PortIsSystemReady(void)
{
    return (tSysInfo.uInit.tFinish.bIF_DispTask != 0);
}

/***********************************************************************************************************************
 * 函数功能    : 常亮亮屏提示钩子
 * 说明(备注)  : 框架在常亮亮屏时调用, 由项目决定提示方式 (本工程为蜂鸣提示)
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortBeepOnLightOn(void)
{
    #if (boardBUZ_EN)
    bBuz_Tweet(LONG_1);
    #endif  /* boardBUZ_EN */
}

#if (boardUSE_OS)

/***********************************************************************************************************************
 * 函数功能    : 绑定显示任务句柄
 * 说明(备注)  : 显示任务创建完成后调用一次; 未绑定时唤醒为空操作
 * 传入参数    : t_handle: 显示任务句柄
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortSetTaskHandle(TaskHandle_t t_handle)
{
    S_tDispTaskHandle = t_handle;
}

/***********************************************************************************************************************
 * 函数功能    : 唤醒显示任务
 * 说明(备注)  : 事件入队/背光点亮后调用; 显示任务从"通知+超时"等待中提前返回,
 *               下一轮 vDisp_EnginePoll 立即处理事件与首帧强刷
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortWakeTask(void)
{
    if (S_tDispTaskHandle != NULL)
        xTaskNotifyGive(S_tDispTaskHandle);
}

#endif  //boardUSE_OS

#endif  /* boardDISPLAY_EN */
