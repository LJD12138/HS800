#include "uni_disp_port.h"

#if (boardDISPLAY_EN)

#if (boardUSE_OS)

//****************************************************Parameter Initialization**************************************************//
static TaskHandle_t S_tDispTaskHandle = NULL;

/***********************************************************************************************************************
 * 函数功能    : 绑定显示任务句柄
 * 说明(备注)  : 显示任务创建完成后调用一次; 未绑定时唤醒为空操作
 * 传入参数    : t_handle: 显示任务句柄
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortSetTaskHandle(TaskHandle_t t_handle)
{
    S_tDispTaskHandle = t_handle;
}

/***********************************************************************************************************************
 * 函数功能    : 唤醒显示任务
 * 说明(备注)  : 事件入队/背光点亮后调用; 显示任务从"通知+超时"等待中提前返回,
 *               下一轮 vDisp_EnginePoll 立即处理事件与首帧强刷
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortWakeTask(void)
{
    if (S_tDispTaskHandle != NULL)
        xTaskNotifyGive(S_tDispTaskHandle);
}

#endif  //boardUSE_OS

#endif  /* boardDISPLAY_EN */
