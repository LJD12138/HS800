/***********************************************************************************************************************
 * 函数功能    : 将 16 进制数组转换为 ASCII 字符串
 * 说明(备注)  : 每个字节展开为 2 字符大写十六进制
 * 传入参数    : p_hex: 输入 16 进制数据; len: 长度
 * 输出参数    : p_ascii: 输出字符串缓冲区 (长度需大于等于 len * 2 + 1)
 * 返回值      : 无
 ************************************************************************************************************************/
void hex2ascii(const unsigned char *p_hex, char *p_ascii, int len)
{
    static const char s_ca_hex_table[] = "0123456789ABCDEF";

    if (p_hex == NULL || p_ascii == NULL || len <= 0)
        return;

    for (int i = 0; i < len; i++)
    {
        p_ascii[i * 2]     = s_ca_hex_table[(p_hex[i] >> 4) & 0x0F];
        p_ascii[i * 2 + 1] = s_ca_hex_table[p_hex[i] & 0x0F];
    }
    p_ascii[len * 2] = '\0';
}

/***********************************************************************************************************************
 * 函数功能    : 单个 Hex 字符转换为数值
 * 说明(备注)  : 不依赖外部 ctype 库，轻量自实现
 * 传入参数    : ch: 输入字符 ('0'~'9', 'a'~'f', 'A'~'F')
 * 输出参数    : 无
 * 返回值      : 对应数值 0~15；若为非法字符返回 -1
 ************************************************************************************************************************/
int sFunc_HexStrToHex(char ch)
{
    if (ch >= '0' && ch <= '9')
        return (ch - '0');
    else if (ch >= 'a' && ch <= 'f')
        return (ch - 'a' + 10);
    else if (ch >= 'A' && ch <= 'F')
        return (ch - 'A' + 10);
    return -1;
}

/***********************************************************************************************************************
 * 函数功能    : 将 16 进制字符串转换为字节数组
 * 说明(备注)  : 每 2 个 Hex 字符拼为一个字节
 * 传入参数    : p_hexstr: 输入字符串; len: 转换后目标字节数组长度
 * 输出参数    : p_hex: 目标字节数组
 * 返回值      : 无
 ************************************************************************************************************************/
void sFunc_2HexStrTo1Hex(const char *p_hexstr, unsigned char *p_hex, int len)
{
    if (p_hexstr == NULL || p_hex == NULL || len <= 0)
        return;

    for (int i = 0; i < len; i++)
    {
        if (p_hexstr[i * 2] == '\0' || p_hexstr[i * 2 + 1] == '\0')
            break;

        int high = sFunc_HexStrToHex(p_hexstr[i * 2]);
        int low  = sFunc_HexStrToHex(p_hexstr[i * 2 + 1]);

        high = (high < 0) ? 0 : high;
        low  = (low < 0) ? 0 : low;

        p_hex[i] = (unsigned char)((high << 4) | low);
    }
}

