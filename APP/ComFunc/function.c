/***********************************************************************************************************************
 * 函数功能    : Hex 字符串数组解析为 16 位整数
 * 说明(备注)  : 移位累加
 * 传入参数    : p_hex: 字符指针; len: 长度
 * 输出参数    : 无
 * 返回值      : 转换后的整数
 ************************************************************************************************************************/
u16 hex_to_int(const u8 *p_hex, u8 len)
{
    u16 result16 = 0;
    u8  result = 0;

    if (p_hex == NULL)
        return 0;

    for (u8 i = 0; i < len; i++)
    {
        if (p_hex[i] >= '0' && p_hex[i] <= '9')
            result = p_hex[i] - '0';
        else if (p_hex[i] >= 'a' && p_hex[i] <= 'f')
            result = p_hex[i] - 'a' + 10;
        else if (p_hex[i] >= 'A' && p_hex[i] <= 'F')
            result = p_hex[i] - 'A' + 10;
        result16 = (result16 << 4) | result;
    }
    return result16;
}

