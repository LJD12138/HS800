/***********************************************************************************************************************
 * 函数功能    : 16位寄存器数组大小端批量转换
 * 说明(备注)  : 修复原原地转换 (dst == src) 时的覆盖 Bug；支持原地与非原地安全转换
 * 传入参数    : p_dst: 目标指针; p_src: 源指针; reg_size: 寄存器字数 (总字节数为 reg_size * 2)
 * 输出参数    : p_dst: 转换后的字节序列
 * 返回值      : true: 成功; false: 入参错误
 ************************************************************************************************************************/
bool bFunc_SwapU16Array(u8 *p_dst, const u8 *p_src, u16 reg_size)
{
    if (p_dst == NULL || p_src == NULL || reg_size == 0)
        return false;

    for (u16 i = 0; i < reg_size; i++)
    {
        u8 b0 = p_src[i * 2];
        u8 b1 = p_src[i * 2 + 1];
        p_dst[i * 2]     = b1;
        p_dst[i * 2 + 1] = b0;
    }
    return true;
}

