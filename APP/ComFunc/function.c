/***********************************************************************************************************************
 * 函数功能    : 二分法在 16 位单调表中定位数值索引
 * 说明(备注)  : 默认表格单调递增
 * 传入参数    : p_buff: 表格指针; array_len: 表长度; dat: 目标数据
 * 输出参数    : 无
 * 返回值      : 最接近的索引下标
 ************************************************************************************************************************/
u8 ucFunc_PositTableU16(const u16 *p_buff, u8 array_len, u16 dat)
{
    u8 begin = 0;
    u8 end;
    u8 middle = 0;

    if (p_buff == NULL || array_len == 0)
        return 0;

    end = (u8)(array_len - 1);

    if (dat >= p_buff[end])
        return end;
    else if (dat <= p_buff[begin])
        return begin;

    while (begin <= end)
    {
        middle = (u8)((begin + end) / 2);
        if (dat == p_buff[middle])
            return middle;

        if (dat > p_buff[middle])
        {
            if (middle + 1 <= end && dat < p_buff[middle + 1])
                return ((dat - p_buff[middle]) <= (p_buff[middle + 1] - dat)) ? middle : (u8)(middle + 1);
            begin = (u8)(middle + 1);
        }
        else
        {
            if (middle > 0 && dat > p_buff[middle - 1])
                return ((p_buff[middle] - dat) <= (dat - p_buff[middle - 1])) ? middle : (u8)(middle - 1);
            if (middle == 0)
                return 0;
            end = (u8)(middle - 1);
        }
    }

    return middle;
}

/***********************************************************************************************************************
 * 函数功能    : 二分法在 32 位单调表中定位数值索引
 * 说明(备注)  : 自动识别表格为递减 (NTC) 还是递增 (PTC)
 * 传入参数    : p_buff: 表格指针; array_len: 表长度; dat: 目标数据
 * 输出参数    : 无
 * 返回值      : 最接近的索引下标
 ************************************************************************************************************************/
u16 usFunc_PositTableU32(const u32 *p_buff, u16 array_len, u32 dat)
{
    u16 begin = 0;
    u16 end;
    u16 middle = 0;

    if (p_buff == NULL || array_len == 0)
        return 0;

    end = (u16)(array_len - 1);

    /* 递减表 (如 NTC 阻值随温度升高而减小) */
    if (p_buff[begin] > p_buff[end])
    {
        if (dat >= p_buff[begin])
            return begin;
        else if (dat <= p_buff[end])
            return end;

        while (begin <= end)
        {
            middle = (u16)((begin + end) / 2);
            if (dat == p_buff[middle])
                return middle;

            if (dat < p_buff[middle])
            {
                if (middle + 1 <= end && dat > p_buff[middle + 1])
                    return ((p_buff[middle] - dat) <= (dat - p_buff[middle + 1])) ? middle : (u16)(middle + 1);
                begin = (u16)(middle + 1);
            }
            else
            {
                if (middle > 0 && dat < p_buff[middle - 1])
                    return ((dat - p_buff[middle]) <= (p_buff[middle - 1] - dat)) ? middle : (u16)(middle - 1);
                if (middle == 0)
                    return 0;
                end = (u16)(middle - 1);
            }
        }
    }
    /* 递增表 (如 PTC) */
    else
    {
        if (dat <= p_buff[begin])
            return begin;
        else if (dat >= p_buff[end])
            return end;

        while (begin <= end)
        {
            middle = (u16)((begin + end) / 2);
            if (dat == p_buff[middle])
                return middle;

            if (dat > p_buff[middle])
            {
                if (middle + 1 <= end && dat < p_buff[middle + 1])
                    return ((dat - p_buff[middle]) <= (p_buff[middle + 1] - dat)) ? middle : (u16)(middle + 1);
                begin = (u16)(middle + 1);
            }
            else
            {
                if (middle > 0 && dat > p_buff[middle - 1])
                    return ((p_buff[middle] - dat) <= (dat - p_buff[middle - 1])) ? middle : (u16)(middle - 1);
                if (middle == 0)
                    return 0;
                end = (u16)(middle - 1);
            }
        }
    }

    return middle;
}

