/***********************************************************************************************************************
 * 函数功能    : 初始化 NTC 配置参数
 * 说明(备注)  : 配置 NTC 额定电阻与分压比
 * 传入参数    : p_val: 配置句柄; sys_vol: 系统基准电压; volt_res: 分压电阻; ntc_res: 额定电阻; hex_x: ADC 满量程; b_x: B值
 * 输出参数    : p_val: 初始化后的配置结构体
 * 返回值      : 无
 ************************************************************************************************************************/
void vNtc_Init(ntc_val_t *p_val, float sys_vol, u16 volt_res, u16 ntc_res, u16 hex_x, u16 b_x)
{
    if (p_val == NULL)
        return;

    p_val->sys_vol  = sys_vol;
    p_val->volt_res = volt_res;
    p_val->ntc_res  = ntc_res;
    p_val->hex_x    = hex_x;
    p_val->b_x      = b_x;
}

/***********************************************************************************************************************
 * 函数功能    : 通过电阻值查表获取温度
 * 说明(备注)  : 二分查找单调递减或递增阻值表
 * 传入参数    : p_buff: 表首地址; zero_index_temp: 0下标对应的物理温度; len: 数组长度; res: 测量阻值
 * 输出参数    : 无
 * 返回值      : 计算得到的温度值 (摄氏度)
 ************************************************************************************************************************/
s16 sNtc_GetTempByRes(const u32 *p_buff, const s16 zero_index_temp, const u16 len, const u32 res)
{
    if (p_buff == NULL || len == 0)
        return zero_index_temp;

    return (s16)(usFunc_PositTableU32(p_buff, len, res) + zero_index_temp);
}

/***********************************************************************************************************************
 * 函数功能    : 通过采样 AD 值计算温度 (定点查表线性插值法)
 * 说明(备注)  : 原理对应 T = 307 - 37 * ln(AD)，消除 math.h 对数库调用与除零硬件异常
 * 传入参数    : us_ad_val: 12 位采样 AD 转换值 (0~4095)
 * 输出参数    : 无
 * 返回值      : int16_t: 计算得出的温度值 (单位: 摄氏度, 范围 -128 ~ 127)
 ************************************************************************************************************************/
int16_t sNtc_CalcTempByAd(uint16_t us_ad_val)
{
	int32_t s_idx;
	int32_t s_rem;
	int32_t s_t0;
	int32_t s_t1;
	int32_t s_t_q8;
	int32_t s_temp;

	/* 1. 安全边界检查与极限情况处理 */
	if (us_ad_val <= 129)
		return 127;     /* AD过小或短路，判定为最高保护温标 127 度 */
	if (us_ad_val >= 4080)
		return 0;       /* AD满量程或开路(NTC断线/丢失)，判定为 0 度，触发 NTC 掉线保护 */

	/* 2. 定点查表与线性插值 (步长 64，右移 6 位) */
	s_idx = (int32_t)(us_ad_val >> 6);
	s_rem = (int32_t)(us_ad_val & 63);

	s_t0 = (int32_t)s_sa_adc_temp_lut_q8[s_idx];
	s_t1 = (int32_t)s_sa_adc_temp_lut_q8[s_idx + 1];

	/* 线性插值并四舍五入: T = T0 + (T1 - T0) * rem / 64 */
	s_t_q8 = s_t0 + (((s_t1 - s_t0) * s_rem) >> 6);
	s_temp = (s_t_q8 + 128) >> 8;

	/* 3. 输出门限钳位 */
	if (s_temp > 127)
		s_temp = 127;
	else if (s_temp < -128)
		s_temp = -128;

	return (int16_t)s_temp;
}

